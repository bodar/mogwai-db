/** A fresh store per graph (every corpus query is a READ, so one store per graph serves them all). */
export const MINT: Record<GraphName, () => GraphStore> = {
  'modern': () => seeded(MODERN_SEED),
  'crew': () => seeded(CREW_SEED),
  'air-routes': airRoutes,
};

// ─────────────────────────── goldens ───────────────────────────

/** A golden: the expected canonical values (`canon.ts`) — or the reference's own error. */
export interface Golden {
  readonly query: string;
  /** `tinkergraph` = generated by `scripts/workload-goldens/generate.ts`; `hand` = derived by reasoning
   *  over the 6-vertex graph (the interim oracle the plan names) and checked value by value. */
  readonly source: 'tinkergraph' | 'hand';
  readonly results?: readonly string[];
  /** The reference REFUSED the query (its error text). */
  readonly error?: string;
  /** For a `hand` golden: why the value is what it is, where it is not obvious. */
  readonly note?: string;
}

export interface GoldenFile {
  readonly header: Record<string, unknown>;
  readonly goldens: Record<string, Golden>;
}

export const readGoldens = (): GoldenFile => JSON.parse(readFileSync(GOLDENS_PATH, 'utf8')) as GoldenFile;

// ─────────────────────────── classification ───────────────────────────

export type Outcome = 'pass' | 'wrong' | 'unverified' | 'declined' | 'error';

export interface Result {
  readonly entry: WorkloadQuery;
  readonly outcome: Outcome;
  readonly depth: number;
  readonly idioms: readonly string[];
  /** The canonical values mogwai answered (absent on a throw). */
  readonly actual?: readonly string[];
  readonly expected?: readonly string[];
  readonly message?: string;
  /** A gating fast-path differential divergence, if any. */
  readonly divergence?: string;
}

/** The canonical answer to `entry` on `store`, bulk spelled out as repeated values. */
export function answer(store: GraphStore, entry: WorkloadQuery): string[] {
  const out: string[] = [];
  for (const f of exec(store).framed(entry.query, {})) {
    const text = canon(f.buf, { orderedLists: entry.lists === 'ordered' });
    for (let i = 0n; i < f.bulk; i++) out.push(text);
  }
  return out;
}

/** Re-spell a golden's values under the entry's list rule: goldens are written with lists ORDERED (the
 *  reference's own emission), so an unordered-list comparison sorts their members, exactly as `canon`
 *  does for mogwai's side. Paths, maps and sets are already canonical. */
export function normalizeGolden(values: readonly string[], entry: WorkloadQuery): string[] {
  if (entry.lists === 'ordered') return [...values];
  return values.map(sortLists);
}

/**
 * Sort the members of every plain List in a canonical string — a tiny recursive-descent reader over the canonical
 * grammar of `canon.ts`. A plain List `[…]` has its members sorted; a tagged bracket (`path[`, `set[`,
 * `v[`, `vp[`, …) keeps its members as written (they are already canonical); a Map `{…}` re-sorts its
 * entries (a member's text may have changed).
 */
export function sortLists(text: string): string {
  let i = 0;
  const group = (open: string, close: string, sort: boolean): string => {
    i++; // past the opener
    const members: string[] = [];
    let cur = '';
    for (;;) {
      if (i >= text.length) throw new Error(`sortLists: unbalanced '${open}' in ${text}`);
      const ch = text[i]!;
      if (ch === close) { i++; break; }
      if (ch === ',') { members.push(cur); cur = ''; i++; continue; }
      cur += item(cur);
    }
    if (cur !== '' || members.length) members.push(cur);
    return open + (sort ? [...members].sort() : members).join(',') + close;
  };
  // Consume one token or group starting at `i`; `prefix` is the member text so far (decides tagging).
  const item = (prefix: string): string => {
    const ch = text[i]!;
    if (ch === '"') { const start = i++; while (text[i] !== '"') { if (text[i] === '\\') i++; i++; } i++; return text.slice(start, i); }
    if (ch === '[') return group('[', ']', !/[A-Za-z]$/.test(prefix));
    if (ch === '{') return group('{', '}', true);
    i++;
    return ch;
  };
  let out = '';
  while (i < text.length) out += item(out);
  return out;
}

/** Compare under the entry's rule; returns null when equal, else a short reason. */
export function compare(entry: WorkloadQuery, actual: readonly string[], expected: readonly string[]): string | null {
  const mode = entry.compare ?? 'unordered';
  if (actual.length !== expected.length) return `${actual.length} result(s), expected ${expected.length}`;
  if (mode === 'count') return null;
  if (mode === 'ordered') {
    const i = actual.findIndex((a, k) => a !== expected[k]);
    return i < 0 ? null : `position ${i}: ${actual[i]} ≠ ${expected[i]}`;
  }
  const a = [...actual].sort(), e = [...expected].sort();
  const missing = e.filter((x) => !a.includes(x)), extra = a.filter((x) => !e.includes(x));
  if (!missing.length && !extra.length && a.every((x, k) => x === e[k])) return null;
  return `multiset differs — missing ${missing.slice(0, 3).join(' ; ') || '(multiplicity)'} · extra ${extra.slice(0, 3).join(' ; ') || '(multiplicity)'}`;
}

/** Run one corpus entry and classify it. */
export function classify(store: GraphStore, mint: () => GraphStore, entry: WorkloadQuery, golden: Golden | undefined): Result {
  const { depth, idioms } = shapeOf(entry.query);
  const base = { entry, depth, idioms };
  let actual: string[];
  try {
    actual = answer(store, entry);
  } catch (e) {
    const message = e instanceof Error ? e.message : String(e);
    if (golden?.error !== undefined) return { ...base, outcome: 'pass', message };
    return { ...base, outcome: e instanceof UnsupportedTraversal ? 'declined' : 'error', message };
  }
  const divergence = gatingDivergences(mint, entry.query)[0];
  const extra = divergence ? { divergence: `${divergence.kind}: ${divergence.detail}` } : {};
  if (!golden) return { ...base, ...extra, outcome: 'unverified', actual };
  if (golden.error !== undefined)
    return { ...base, ...extra, outcome: 'wrong', actual, message: `the reference REFUSES this query (${golden.error}) but mogwai answered` };
  const expected = normalizeGolden(golden.results ?? [], entry);
  const why = compare(entry, actual, expected);
  return why === null
    ? { ...base, ...extra, outcome: 'pass', actual, expected }
    : { ...base, ...extra, outcome: 'wrong', actual, expected, message: why };
}

/** Run the whole corpus (or the entries `only` admits). One store per graph — every entry is a read. */
export function runWorkload(only: (e: WorkloadQuery) => boolean = () => true): Result[] {
  const goldens = readGoldens().goldens;
  const stores = new Map<GraphName, GraphStore>();
  const results: Result[] = [];
  for (const entry of CORPUS) {
    if (!only(entry)) continue;
    let store = stores.get(entry.graph);
    if (!store) stores.set(entry.graph, store = MINT[entry.graph]());
    const golden = goldens[entry.id];
    const usable = golden && golden.query === entry.query ? golden : undefined;
    results.push(classify(store, MINT[entry.graph], entry, usable));
  }
  return results;
}

// ─────────────────────────── shape: depth + idioms ───────────────────────────

/** The parsed step tree, root chain. */
const chainOf = (query: string): readonly Step[] => stepChain(parseGremlin(query), NO_PARAMS);

/**
 * CHILD-TRAVERSAL nesting depth, from the parsed step tree (`ir/walk.ts`'s child positions), not from
 * parentheses — a predicate's parens (`P.gt(30)`) are not a child. 0 = no child traversal at all;
 * `where(__.out())` is 1; `project().by(__.out().where(__.in()))` is 2.
 */
export function nestingDepth(chain: readonly Step[]): number {
  const read = rawBodies(NO_PARAMS);
  let max = 0;
  for (const s of chain) eachChildChain(s, read, (c) => { max = Math.max(max, 1 + nestingDepth(c)); });
  return max;
}

/** Every (step name, depth, next sibling name) in the tree. */
function* stepsDeep(chain: readonly Step[], depth = 0): Generator<{ name: string; depth: number; next?: string; rest: readonly Step[] }> {
  const read = rawBodies(NO_PARAMS);
  for (let k = 0; k < chain.length; k++) {
    const s = chain[k]!;
    yield { name: s.name, depth, next: chain[k + 1]?.name, rest: chain.slice(k + 1) };
    const kids: (readonly Step[])[] = [];
    eachChildChain(s, read, (c) => kids.push(c));
    for (const c of kids) yield* stepsDeep(c, depth + 1);
  }
}

/** The idiom families a query exercises, derived from its step tree so the tagging cannot drift. */
export const IDIOMS: readonly [string, (steps: ReturnType<typeof collect>) => boolean][] = [
  ['filter', (s) => s.some((x) => ['has', 'hasLabel', 'hasId', 'hasNot', 'is', 'filter', 'not', 'and', 'or'].includes(x.name))],
  ['where-subquery', (s) => s.some((x) => x.name === 'where')],
  ['project/by', (s) => s.some((x) => x.name === 'project')],
  ['nested project', (s) => s.some((x) => x.name === 'project' && x.depth > 0)],
  ['group/groupCount', (s) => s.some((x) => x.name === 'group' || x.name === 'groupCount')],
  ['order/limit', (s) => s.some((x) => ['order', 'limit', 'range', 'tail', 'skip'].includes(x.name))],
  ['repeat', (s) => s.some((x) => x.name === 'repeat')],
  ['path', (s) => s.some((x) => x.name === 'path' || x.name === 'tree' || x.name === 'simplePath')],
  ['path-as-value', (s) => s.some((x) => x.name === 'path' && x.rest.some((r) => r.name !== 'by'))],
  ['match', (s) => s.some((x) => x.name === 'match')],
  ['select/as', (s) => s.some((x) => x.name === 'select')],
  ['coalesce/optional/choose', (s) => s.some((x) => ['coalesce', 'optional', 'choose'].includes(x.name))],
  ['union', (s) => s.some((x) => x.name === 'union')],
  ['local/map/flatMap', (s) => s.some((x) => ['local', 'map', 'flatMap'].includes(x.name))],
  ['aggregate/cap', (s) => s.some((x) => ['aggregate', 'cap', 'sideEffect'].includes(x.name))],
  ['reduce (count/sum/mean/fold)', (s) => s.some((x) => ['count', 'sum', 'mean', 'min', 'max', 'fold'].includes(x.name))],
  ['collection re-entry (unfold)', (s) => s.some((x) => x.name === 'unfold')],
  ['sack/math/string', (s) => s.some((x) => ['sack', 'math', 'toUpper', 'toLower', 'concat'].includes(x.name))],
  ['element maps', (s) => s.some((x) => ['valueMap', 'elementMap', 'properties'].includes(x.name))],
];

const collect = (query: string) => [...stepsDeep(chainOf(query))];

export function shapeOf(query: string): { depth: number; idioms: string[] } {
  const chain = chainOf(query);
  const steps = collect(query);
  return { depth: nestingDepth(chain), idioms: IDIOMS.filter(([, has]) => has(steps)).map(([name]) => name) };
}

// ─────────────────────────── reporting ───────────────────────────

const OUTCOMES: readonly Outcome[] = ['pass', 'wrong', 'unverified', 'declined', 'error'];

function row(label: string, rs: readonly Result[]): string {
  const n = (o: Outcome) => rs.filter((r) => r.outcome === o).length;
  const answered = rs.filter((r) => r.outcome !== 'declined' && r.outcome !== 'error').length;
  return `  ${label.padEnd(32)} ${String(rs.length).padStart(4)}  ` +
    OUTCOMES.map((o) => String(n(o)).padStart(11)).join('') +
    `   ${rs.length ? ((100 * answered) / rs.length).toFixed(0).padStart(3) : '  -'}%`;
}

/** The full human report: overall, by source, by graph, by nesting depth, by idiom. */
export function report(results: readonly Result[]): string {
  const head = `  ${''.padEnd(32)} ${'n'.padStart(4)}  ${OUTCOMES.map((o) => o.padStart(11)).join('')}   answered`;
  const lines = ['L6 workload', head, row('ALL', results), '  — by source'];
  const by = (key: (r: Result) => string[]) => {
    const groups = new Map<string, Result[]>();
    for (const r of results) for (const k of key(r)) (groups.get(k) ?? groups.set(k, []).get(k)!).push(r);
    return [...groups.entries()].sort(([a], [b]) => a.localeCompare(b));
  };
  for (const [k, rs] of by((r) => [r.entry.source])) lines.push(row(k, rs));
  lines.push('  — by graph');
  for (const [k, rs] of by((r) => [r.entry.graph])) lines.push(row(k, rs));
  lines.push('  — by child-nesting depth');
  for (const [k, rs] of by((r) => [`depth ${r.depth}`])) lines.push(row(k, rs));
  lines.push('  — by idiom (a query counts under every idiom it uses)');
  for (const [k, rs] of by((r) => [...r.idioms])) lines.push(row(k, rs));
  const wrong = results.filter((r) => r.outcome === 'wrong');
  if (wrong.length) {
    lines.push('', `  ✗ ${wrong.length} WRONG ANSWER(S):`);
    for (const r of wrong) lines.push(`    ${r.entry.id}  ${r.entry.query}`, `      ${r.message}`,
      `      expected ${JSON.stringify(r.expected)}`, `      actual   ${JSON.stringify(r.actual)}`);
  }
  const divergent = results.filter((r) => r.divergence);
  if (divergent.length) {
    lines.push('', `  ✗ ${divergent.length} FAST-PATH DIFFERENTIAL DIVERGENCE(S):`);
    for (const r of divergent) lines.push(`    ${r.entry.id}  ${r.entry.query}`, `      ${r.divergence}`);
  }
  const errors = results.filter((r) => r.outcome === 'error');
  if (errors.length) {
    lines.push('', `  ✗ ${errors.length} INTERNAL ERROR(S):`);
    for (const r of errors) lines.push(`    ${r.entry.id}  ${r.entry.query}`, `      ${r.message?.slice(0, 200)}`);
  }
  const declined = results.filter((r) => r.outcome === 'declined');
  if (declined.length) {
    lines.push('', `  ${declined.length} declined (UnsupportedTraversal):`);
    for (const r of declined) lines.push(`    ${r.entry.id.padEnd(30)} d${r.depth}  ${r.entry.query}`);
  }
  return lines.join('\n');
}

// ─────────────────────────── baseline ───────────────────────────

export interface Baseline {
  readonly note: string;
  readonly counts: Record<Outcome, number>;
  /** Every corpus id → its recorded outcome. */
  readonly outcomes: Record<string, Outcome>;
  /** Every recorded WRONG answer, with the reason a human wrote for keeping it on the books. */
  readonly wrong: Record<string, string>;
  /** Every recorded fast-path divergence, with its reason. */
  readonly divergent: Record<string, string>;
}

export const UNTRIAGED = 'UNTRIAGED';

export const readBaseline = (): Baseline => JSON.parse(readFileSync(BASELINE_PATH, 'utf8')) as Baseline;

/** What a re-record should write: the new outcomes, carrying forward every written reason. */
export function nextBaseline(results: readonly Result[], prior: Baseline | null): Baseline {
  const counts = Object.fromEntries(OUTCOMES.map((o) => [o, results.filter((r) => r.outcome === o).length])) as Record<Outcome, number>;
  const outcomes: Record<string, Outcome> = {};
  const wrong: Record<string, string> = {};
  const divergent: Record<string, string> = {};
  for (const r of results) {
    outcomes[r.entry.id] = r.outcome;
    if (r.outcome === 'wrong') wrong[r.entry.id] = prior?.wrong[r.entry.id] ?? `${UNTRIAGED}: ${r.message}`;
    if (r.divergence) divergent[r.entry.id] = prior?.divergent[r.entry.id] ?? `${UNTRIAGED}: ${r.divergence.slice(0, 200)}`;
  }
  return {
    note: 'L6 workload ratchet — written by `mise run workload-record`. A `wrong`/`divergent` entry must carry a human reason; an UNTRIAGED one fails the test.',
    counts, outcomes, wrong, divergent,
  };
}

export const ANSWERED: ReadonlySet<Outcome> = new Set<Outcome>(['pass', 'unverified', 'wrong']);
