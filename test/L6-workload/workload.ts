// L6 — the realistic-workload suite: run every corpus query, classify it, compare to its golden.
//
// Shared by the test (`workload.test.ts`, the ratchet), the recorder (`record.ts`, `mise run
// workload-record`) and the one-off golden generator (`scripts/workload-goldens/generate.ts`).
//
// OUTCOMES:
//   pass       — answered, and the answer equals the golden under the query's comparison;
//   wrong      — answered, and the answer DIFFERS from the golden. The most important finding there is;
//                never baselined without a written reason (baseline.json `wrong`);
//   unverified — answered, but no golden exists yet for it (the goldens are generated offline against
//                TinkerGraph; until a run of the generator covers a query, only that it ANSWERS is held);
//   declined   — a clean `UnsupportedTraversal` (fail-closed: a gap, not a defect);
//   error      — any other throw: an internal error, which the fail-closed contract forbids.
// Separately, every answered query runs the L5 fast-path DIFFERENTIAL (fast paths on vs all off — the
// generic lowering is the semantic authority), which needs no golden: a divergence is a defect either way.
