// The decline attribution (cc1-shrink + cc1-classify, docs/2026-11-15-compositional-coverage-plan.md
// §3 Phase 1): shrink every decline the Phase 0 instruments see to a minimal core, cluster the cores by
// signature, classify each cluster, and rank by reach. Engine and rationale: test/L5-properties/attribution.ts.
//
//   bun scripts/coverage-attribution.ts      (mise run attribution) — writes .logs/coverage-attribution.md
//   ATTRIBUTION_PER_SEED=n                   coverage sample per seed per profile (default 1000)
//   ATTRIBUTION_HOST_CASES=n                 host-closure cases at seed 42 (default 200, the ratchet sample)
//
// An instrument, not a gate: it is not in `ci`. The committed G1 summary in the plan doc is written by
// hand from the report's "G1" block — the figure is an escalation checkpoint for the owner.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  Attributor, cluster, collect, KLASS_NAME, share, SOURCES, totals, WEIGHT,
  type Attributed, type Cluster, type Internal, type Klass,
} from '../test/L5-properties/attribution.ts';

const perSeed = Number(process.env.ATTRIBUTION_PER_SEED ?? 1000);
const hostCases = Number(process.env.ATTRIBUTION_HOST_CASES ?? 200);
const t0 = performance.now();
const internal: Internal[] = [];

const declines = collect({ perSeed, hostCases }, internal);
const tCollect = performance.now();
const attributor = new Attributor(internal);
const rows: Attributed[] = [];
let failed = 0;
for (const d of declines) {
  try { rows.push({ decline: d, core: attributor.attribute(d) }); } catch (e) {
    failed++;
    internal.push({ query: d.query, error: `attribution itself threw: ${String(e).slice(0, 200)}`, where: 'attribution' });
  }
}
const clusters = cluster(rows);
const secs = (ms: number) => `${(ms / 1000).toFixed(1)}s`;
const tEnd = performance.now();

// ─────────────── report ───────────────
const KLASSES: Klass[] = ['a', 'b', 'c', 'd'];
const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
const esc = (s: string) => s.replace(/\|/g, '\\|');
const deep = totals(rows, (r) => r.decline.depth >= 2);
const all = totals(rows);
const perSource = SOURCES.map((s) => ({ s, t: totals(rows, (r) => r.decline.source === s), deep: totals(rows, (r) => r.decline.source === s && r.decline.depth >= 2) }));
const sitems = new Map<string, number>();
for (const r of rows) if (r.core.klass === 'a') sitems.set(r.core.sitem, (sitems.get(r.core.sitem) ?? 0) + WEIGHT[r.decline.source]);
const totalA = [...sitems.values()].reduce((a, b) => a + b, 0);

const klassRow = (label: string, t: ReturnType<typeof totals>) =>
  `| ${label} | ${KLASSES.map((k) => `${t.count[k]} (w ${t.weighted[k]}, ${pct(share(t, k))})`).join(' | ')} |`;

const clusterRow = (c: Cluster, i: number) =>
  `| ${i + 1} | ${c.reach} | (${c.klass}) ${KLASS_NAME[c.klass]}${c.mixed ? '*' : ''} | ${c.klass === 'a' ? c.sitem : '—'} | ${esc(c.host || '—')} | \`${esc(c.signature)}\` | ${SOURCES.map((s) => c.bySource[s]).join('/')} | ${c.depths.join(',')} | \`${esc(c.example)}\` |`;

const lines: string[] = [];
lines.push(`# Coverage attribution — ${new Date().toISOString().slice(0, 10)}`, '');
lines.push(`Generated by \`mise run attribution\` (scripts/coverage-attribution.ts). Sample: coverage ${perSeed}/seed × 3 seeds per profile, host-closure ${hostCases} cases at seed 42, all ${'L6'} workload queries.`);
lines.push(`Weights (reach): ${SOURCES.map((s) => `${s} ×${WEIGHT[s]}`).join(', ')}. Runtime ${secs(tEnd - t0)} (collect ${secs(tCollect - t0)}, shrink+classify ${secs(tEnd - tCollect)}; ${attributor.tried} candidates compiled).`, '');
lines.push('## G1', '');
const deepW = KLASSES.reduce((a, k) => a + deep.weighted[k], 0);
lines.push(`**Weighted share of class (a) seam among declines at child-nesting depth ≥ 2: ${pct(share(deep, 'a'))}** (${deep.count.a} of ${KLASSES.reduce((a, k) => a + deep.count[k], 0)} declines; weighted ${deep.weighted.a} of ${deepW}; ${pct(deep.weighted.a / Math.max(1, deepW - deep.weighted.d))} with (d) noise left out of the denominator).`, '');
lines.push(`| scope | (a) seam | (b) step | (c) platform | (d) noise |`, '|---|---|---|---|---|');
lines.push(klassRow('all depths', all), klassRow('depth ≥ 2', deep));
for (const p of perSource) lines.push(klassRow(`${p.s}`, p.t), klassRow(`${p.s}, depth ≥ 2`, p.deep));
lines.push('', `Seam (a) by S-item (weighted, heuristic — see attribution.ts): ${[...sitems].sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${pct(v / (totalA || 1))}`).join(', ')}`, '');
lines.push('## Clusters', '');
lines.push(`${clusters.length} clusters over ${rows.length} declines. Reach = Σ source weight. Sources = ${SOURCES.join('/')}. Depth = the ORIGINAL queries' child-nesting depths. \`*\` = members disagree on class (majority shown).`, '');
lines.push('| # | reach | class | S | host | signature | sources | depth | example minimal core |', '|---|---|---|---|---|---|---|---|---|');
clusters.forEach((c, i) => lines.push(clusterRow(c, i)));
lines.push('', '## Top clusters — core, the query it came from, and why the class', '');
clusters.slice(0, 40).forEach((c, i) => {
  lines.push(`${i + 1}. \`${c.example}\` — (${c.klass}) ${c.why}`, `   from \`${c.exampleFrom}\``);
});
lines.push('', '## Internal errors (defects)', '');
if (internal.length === 0) lines.push('none');
const seenInternal = new Set<string>();
for (const i of internal) {
  const key = `${i.query}\u0000${i.error}`;
  if (seenInternal.has(key)) continue;
  seenInternal.add(key);
  lines.push(`- \`${esc(i.query)}\` — ${esc(i.error)} (${i.where})`);
}
if (failed) lines.push('', `${failed} declines could not be attributed (the attribution threw; listed above).`);

const out = join(import.meta.dir, '..', '.logs', 'coverage-attribution.md');
mkdirSync(join(import.meta.dir, '..', '.logs'), { recursive: true });
writeFileSync(out, lines.join('\n') + '\n');

console.log(`attribution: ${rows.length} declines → ${clusters.length} clusters in ${secs(tEnd - t0)}`);
console.log(`G1: class (a) seam = ${pct(share(deep, 'a'))} of weighted declines at depth ≥ 2 (all depths: ${pct(share(all, 'a'))})`);
console.log(`classes (weighted, all depths): ${KLASSES.map((k) => `(${k}) ${KLASS_NAME[k]} ${pct(share(all, k))}`).join(', ')}`);
console.log(`internal errors: ${seenInternal.size}`);
console.log(`report: ${out}`);
